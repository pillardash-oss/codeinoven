#!/usr/bin/env bun
/**
 * Generates the Windows Package Manager (winget) manifests for a published
 * CodeInOven release.
 *
 * winget pins one version and one installer hash per manifest folder, so every
 * release needs a fresh set of three files under
 * `packaging/winget/manifests/<letter>/<publisher>/<package>/<version>/`:
 *
 *   <Identifier>.yaml                 the version manifest
 *   <Identifier>.installer.yaml       the installer manifest
 *   <Identifier>.locale.en-US.yaml    the default-locale manifest
 *
 * The installer hash and the GitHub asset name come from the release mirror's
 * own `RELEASE.json`, so the manifest can never drift from the bytes GitHub
 * published. Override any value with a flag to regenerate offline.
 *
 * Usage (from the repository root):
 *   bun scripts/winget-manifest.ts
 *   bun scripts/winget-manifest.ts --version 0.5.62 --sha256 <hex> --date 2026-11-01
 */
import { readFileSync } from 'node:fs'
import { mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

/**
 * winget requires `<publisher>.<package>` with no spaces, and the folder layout
 * must mirror the identifier exactly: the first segment sets the top folder.
 */
const PACKAGE_IDENTIFIER = 'PillardashSolutions.CodeInOven'
const PUBLISHER = 'Pillardash Solutions Limited'
const PACKAGE_NAME = 'CodeInOven'
const PACKAGE_LOCALE = 'en-US'
const MANIFEST_VERSION = '1.10.0'
const GITHUB_REPOSITORY = 'pillardash-oss/codeinoven'
const MIRROR_ORIGIN = 'https://dl.codeinoven.com'
const WEBSITE_URL = 'https://codeinoven.com'
const REPO_URL = `https://github.com/${GITHUB_REPOSITORY}`
const GENERATED_HEADER = '# Generated by scripts/winget-manifest.ts. Do not edit by hand.'

type Flags = Map<string, string>

type ReleaseArtifact = {
  source: string
  platform: string
  sha256: string
}

type ReleaseInfo = {
  version: string
  tag: string
  publishedAt: string
  artifacts: ReleaseArtifact[]
}

function write(line: string): void {
  process.stdout.write(`${line}\n`)
}

function fail(message: string): never {
  write(`::error::${message}`)
  process.exit(1)
}

function parseFlags(argv: string[]): Flags {
  const flags: Flags = new Map()
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (!argument.startsWith('--')) continue
    const next = argv[index + 1]
    if (next === undefined || next.startsWith('--')) {
      flags.set(argument.slice(2), 'true')
    } else {
      flags.set(argument.slice(2), next)
      index += 1
    }
  }
  return flags
}

/** Plain YAML scalars are safe for simple values; anything else is JSON-quoted. */
function scalar(value: string): string {
  if (/^[A-Za-z0-9][A-Za-z0-9 .,_/&+-]*$/.test(value)) return value
  return JSON.stringify(value)
}

function line(key: string, value: string): string {
  return `${key}: ${scalar(value)}`
}

function localVersion(): string {
  const packageJson = JSON.parse(readFileSync(resolve('package.json'), 'utf8')) as {
    version: string
  }
  return packageJson.version
}

async function fetchRelease(channel: string): Promise<ReleaseInfo> {
  const url = `${MIRROR_ORIGIN}/${channel}/RELEASE.json`
  const response = await fetch(url)
  if (!response.ok) fail(`Could not read ${url}: HTTP ${response.status}`)
  return (await response.json()) as ReleaseInfo
}

function releaseDate(publishedAt: string): string {
  const parsed = new Date(publishedAt)
  if (Number.isNaN(parsed.getTime())) fail(`Invalid release date: ${publishedAt}`)
  return parsed.toISOString().slice(0, 10)
}

function versionManifest(version: string): string {
  return `${GENERATED_HEADER}\n${[
    line('PackageIdentifier', PACKAGE_IDENTIFIER),
    line('PackageVersion', version),
    line('DefaultLocale', PACKAGE_LOCALE),
    line('ManifestType', 'version'),
    line('ManifestVersion', MANIFEST_VERSION)
  ].join('\n')}\n`
}

function installerManifest(
  version: string,
  installerUrl: string,
  sha256: string,
  date: string
): string {
  const body = [
    line('PackageIdentifier', PACKAGE_IDENTIFIER),
    line('PackageVersion', version),
    line('InstallerLocale', PACKAGE_LOCALE),
    'Platform:',
    '  - Windows.Desktop',
    line('MinimumOSVersion', '10.0.0.0'),
    // The NSIS target is electron-builder's oneClick, perMachine:false installer,
    // so it installs per user and installs silently with the nullsoft `/S`.
    line('InstallerType', 'nullsoft'),
    line('Scope', 'user'),
    'InstallModes:',
    '  - interactive',
    '  - silent',
    '  - silentWithProgress',
    line('UpgradeBehavior', 'install'),
    line('ReleaseDate', date),
    'Installers:',
    '  - Architecture: x64',
    `    ${line('InstallerUrl', installerUrl)}`,
    `    ${line('InstallerSha256', sha256.toUpperCase())}`,
    '    AppsAndFeaturesEntries:',
    `      - ${line('DisplayName', PACKAGE_NAME)}`,
    `        ${line('Publisher', PUBLISHER)}`,
    line('ManifestType', 'installer'),
    line('ManifestVersion', MANIFEST_VERSION)
  ]
  return `${GENERATED_HEADER}\n${body.join('\n')}\n`
}

function localeManifest(version: string, tag: string): string {
  const body = [
    line('PackageIdentifier', PACKAGE_IDENTIFIER),
    line('PackageVersion', version),
    line('PackageLocale', PACKAGE_LOCALE),
    line('Publisher', PUBLISHER),
    line('PublisherUrl', WEBSITE_URL),
    line('PublisherSupportUrl', `${REPO_URL}/issues`),
    line('PrivacyUrl', `${WEBSITE_URL}/privacy`),
    line('Author', PUBLISHER),
    line('PackageName', PACKAGE_NAME),
    line('PackageUrl', WEBSITE_URL),
    line('License', 'MIT'),
    line('LicenseUrl', `${REPO_URL}/blob/main/LICENSE`),
    line('Copyright', `Copyright (c) ${PUBLISHER}`),
    line('CopyrightUrl', `${REPO_URL}/blob/main/LICENSE`),
    line('ShortDescription', 'Desktop workstation for coordinated agentic software engineering.'),
    line(
      'Description',
      'CodeInOven runs and coordinates multiple coding agents across your projects from one desktop window, with scoped permissions, embedded browser previews, and git worktree isolation.'
    ),
    'Tags:',
    '  - ai',
    '  - agents',
    '  - developer-tools',
    '  - coding-assistant',
    '  - electron',
    line('ReleaseNotesUrl', `${REPO_URL}/releases/tag/${tag}`),
    line('ManifestType', 'defaultLocale'),
    line('ManifestVersion', MANIFEST_VERSION)
  ]
  return `${GENERATED_HEADER}\n${body.join('\n')}\n`
}

const flags = parseFlags(Bun.argv.slice(2))
const channel = flags.get('channel') ?? 'stable'
const outputRoot = resolve(flags.get('out') ?? 'packaging/winget/manifests')

const version = flags.get('version') ?? localVersion()
const needsRelease = !flags.has('sha256') || !flags.has('date')
const release = needsRelease ? await fetchRelease(channel) : null

const artifact = release?.artifacts.find((entry) => entry.platform === 'windows')
const sha256 = flags.get('sha256') ?? artifact?.sha256
if (!sha256) fail(`No Windows installer hash found for version ${version} in ${channel}`)

const tag = release?.tag ?? `v${version}`
const assetName = artifact?.source ?? `${PACKAGE_NAME.toLowerCase()}-${version}-setup.exe`
const date =
  flags.get('date') ??
  (release ? releaseDate(release.publishedAt) : releaseDate(new Date().toISOString()))
const installerUrl = flags.get('url') ?? `${REPO_URL}/releases/download/${tag}/${assetName}`

const [publisherSegment, packageSegment] = PACKAGE_IDENTIFIER.split('.')
const targetDirectory = join(
  outputRoot,
  publisherSegment.charAt(0).toLowerCase(),
  publisherSegment,
  packageSegment,
  version
)

mkdirSync(targetDirectory, { recursive: true })
const files: Array<[string, string]> = [
  [`${PACKAGE_IDENTIFIER}.yaml`, versionManifest(version)],
  [`${PACKAGE_IDENTIFIER}.installer.yaml`, installerManifest(version, installerUrl, sha256, date)],
  [`${PACKAGE_IDENTIFIER}.locale.${PACKAGE_LOCALE}.yaml`, localeManifest(version, tag)]
]

for (const [name, contents] of files) {
  const path = join(targetDirectory, name)
  // Bun.write needs the directory to exist, which mkdirSync above guarantees.
  await Bun.write(path, contents)
  write(`wrote ${dirname(path)}/${name}`)
}

write(`winget version ${version}: ${installerUrl}`)
